#!/usr/bin/env node
// Summarizes flutter/coverage/lcov.info into coverage-summary/flutter.json
// (contract amendment A10).
//
// `flutter test --branch-coverage` writes DA and BRDA records but no BRF/BRH,
// and flutter test collects no function coverage at all (no FN/FNDA/FNF/FNH:
// flutter_tools test/coverage_collector.dart never passes functionCoverage to
// package:coverage). Line and branch totals come from LF/LH and BRF/BRH when
// present and are computed from DA and BRDA otherwise. Functions come from
// FN/FNDA when lcov.info has them; otherwise they are derived the way
// package:coverage derives them (see dartFunctions below).
//
// The gate is the whole of lib/ minus EXCLUDED (A10), so gate.include equals
// whole.include and every file left out is listed with its A10 category.
//
// Honesty checks, reported in the JSON and on stderr:
//   - lib/ files missing from lcov.info ("unmeasured"): no test loaded them, or
//     they have no executable lines. Either load them from a test or add them
//     to EXCLUDED with a reason. An unmeasured file has no line count, so a
//     percentage over the rest would overstate coverage: while any file in a
//     scope is unmeasured, that scope's pct values are null and `complete` is
//     false. The covered/total counts stay, labeled as measured files only.
//   - every exclusion names an A10 category, and every EXCLUDED glob matches
//     a file (a stale exclusion is flagged).
//   - every `// coverage:ignore-*` comment in lib/, with its reason text. An
//     ignore without a reason is flagged, so is an ignore-line or
//     ignore-start whose reason names no A10 category (the A10 value, e.g.
//     `// coverage:ignore-line dead: pending delete decision`), and so is an
//     ignore-file on a file EXCLUDED does not list with an A10 category.
//
// flutter-summary.test.mjs (node --test, run by flutter.sh) checks the lcov
// parser, the function scanner and totals, and the ignore checks.
//
// Usage:
//   node flutter-summary.mjs --lcov <lcov.info> --pkg <flutter dir> --out <json>
//     [--command "<cmd>"]... [--tests-exit <n>] [--contracts <status>]
//     [--contracts-harness <status>] [--enforce]
//   node flutter-summary.mjs --functions <file.dart>...
//     prints the functions dartFunctions finds, as JSON (for checking it)
// --contracts is validate.mjs on the tests' factory output (--out flutter);
// --contracts-harness is validate.mjs on the support self-test's round-trip
// (--out flutter-harness), which never counts as factory output.
// --enforce exits 2 when the gate is under 95% lines, branches or functions,
// or a check above fails. Without it the script exits 0 once the summary is
// written.

