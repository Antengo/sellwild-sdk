function parseArgs(argv) {
  const args = { commands: [], enforce: false };
  for (let i = 0; i < argv.length; i++) {
    const flag = argv[i];
    const value = () => {
      if (i + 1 >= argv.length) throw new Error(`${flag} needs a value`);
      return argv[++i];
    };
    switch (flag) {
      case '--lcov': args.lcov = value(); break;
      case '--pkg': args.pkg = value(); break;
      case '--out': args.out = value(); break;
      case '--command': args.commands.push(value()); break;
      case '--tests-exit': args.testsExit = Number(value()); break;
      case '--contracts': args.contracts = value(); break;
      case '--contracts-harness': args.contractsHarness = value(); break;
      case '--enforce': args.enforce = true; break;
      default: throw new Error(`unknown argument ${flag}`);
    }
  }
  for (const required of ['lcov', 'pkg', 'out']) {
    if (!args[required]) throw new Error(`--${required} is required`);
  }
  return args;
}

export function parseLcov(text) {
  const files = new Map();
  let current = null;
  const int = (s) => Number.parseInt(s, 10);
  for (const raw of text.split('\n')) {
    const line = raw.trim();
    if (line.startsWith('SF:')) {
      current = {
        path: line.slice(3),
        da: new Map(),
        brda: [],
        fn: new Map(),
        fnda: new Map(),
        summary: {},
      };
      files.set(current.path, current);
      continue;
    }
    if (!current) continue;
    if (line === 'end_of_record') {
      current = null;
      continue;
    }
    const colon = line.indexOf(':');
    if (colon < 0) continue;
    const tag = line.slice(0, colon);
    const body = line.slice(colon + 1);
    const parts = body.split(',');
    switch (tag) {
      case 'DA': {
        const lineNo = int(parts[0]);
        current.da.set(lineNo, (current.da.get(lineNo) ?? 0) + int(parts[1]));
        break;
      }
      case 'BRDA':
        current.brda.push({ line: int(parts[0]), block: parts[1], branch: parts[2], taken: parts[3] });
        break;
      case 'FN':
        current.fn.set(parts.slice(1).join(','), int(parts[0]));
        break;
      case 'FNDA':
        current.fnda.set(parts.slice(1).join(','), int(parts[0]));
        break;
      case 'LF': case 'LH': case 'BRF': case 'BRH': case 'FNF': case 'FNH':
        current.summary[tag] = int(body);
        break;
      default:
        break;
    }
  }
  return files;
}

function counts(covered, total) {
  return { covered, total, pct: total === 0 ? null : Math.round((covered / total) * 10000) / 100 };
}

// ── Dart functions ──────────────────────────────────────────────────────────
//
// package:coverage's function coverage (which flutter test does not turn on)
// takes every non-implicit, non-abstract function the VM lists for a library
// and its classes, and counts one as hit when its declaration line has a
// line hit. The VM records a function's entry on the line where the
// declaration starts: its first annotation, else its first modifier or type.
// dartFunctions finds the same declarations in the source: top-level
// functions, getters and setters, and the methods, getters, setters,
// operators and constructors (bodyless ones included) of classes, mixins,
// enums and extensions, plus the constructor the compiler adds to an enum
// that declares none (the VM lists it too). Abstract and external members,
// redirecting factories (no body of their own) and fields are not
// functions; closures and local functions are not counted, as in
// package:coverage. It is a scanner, not a parser: it needs code that
// compiles, which flutter test has just proved.
//
// Checked on 2026-09-24: the same declarations and start lines as the
// analyzer's AST (package:analyzer 10.1.0) on 80,535 functions in 4,046
// files (this package, Flutter's framework, flutter_tools, flutter_test and
// 118 pub packages), and the same function list and hits as a real
// package:coverage run with function coverage on over this package's tests.

const DART_OPERATORS = [
  '>>>=', '...?', '>>=', '<<=', '??=', '~/=', '>>>', '...', '?..',
  '=>', '==', '!=', '<=', '>=', '&&', '||', '??', '?.', '..', '++', '--',
  '+=', '-=', '*=', '/=', '%=', '&=', '|=', '^=', '<<', '>>', '~/',
];
const IDENT_START = /[A-Za-z_$]/;
const IDENT_PART = /[A-Za-z0-9_$]/;

function skipBlockComment(src, i, state) {
  let depth = 0;
  while (i < src.length) {
    if (src[i] === '/' && src[i + 1] === '*') {
      depth++;
      i += 2;
    } else if (src[i] === '*' && src[i + 1] === '/') {
      depth--;
      i += 2;
      if (depth === 0) return i;
    } else {
      if (src[i] === '\n') state.line++;
      i++;
    }
  }
  return i;
}

// From just after `${` to just after its closing `}`.
function skipInterpolation(src, i, state) {
  let depth = 0;
  while (i < src.length) {
    const c = src[i];
    if (c === '\n') {
      state.line++;
      i++;
    } else if (c === '/' && src[i + 1] === '/') {
      while (i < src.length && src[i] !== '\n') i++;
    } else if (c === '/' && src[i + 1] === '*') {
      i = skipBlockComment(src, i, state);
    } else if (c === "'" || c === '"' || (c === 'r' && (src[i + 1] === "'" || src[i + 1] === '"') && !IDENT_PART.test(src[i - 1] ?? ''))) {
      i = skipString(src, i, state);
    } else if (c === '{') {
      depth++;
      i++;
    } else if (c === '}') {
      i++;
      if (depth === 0) return i;
      depth--;
    } else {
      i++;
    }
  }
  return i;
}

// From a string's first character (its quote, or the `r` of a raw string) to
// just after its closing quote.
function skipString(src, i, state) {
  const raw = src[i] === 'r';
  if (raw) i++;
  const q = src[i];
  const triple = src[i + 1] === q && src[i + 2] === q;
  i += triple ? 3 : 1;
  while (i < src.length) {
    const c = src[i];
    if (!raw && c === '\\') {
      if (src[i + 1] === '\n') state.line++;
      i += 2;
    } else if (triple ? c === q && src[i + 1] === q && src[i + 2] === q : c === q) {
      return i + (triple ? 3 : 1);
    } else if (!raw && c === '$' && src[i + 1] === '{') {
      i = skipInterpolation(src, i + 2, state);
    } else {
      if (c === '\n') state.line++;
      i++;
    }
  }
  return i;
}

// Tokens of Dart source: { t: 'id' | 'str' | 'num' | 'op', v, line, pos, end }.
// Comments are dropped and a string (interpolations included) is one token.
export function lexDart(src) {
  const tokens = [];
  const state = { line: 1 };
  let i = src.startsWith('#!') ? src.indexOf('\n') : 0;
  if (i < 0) return tokens;
  while (i < src.length) {
    const c = src[i];
    const line = state.line;
    const pos = i;
    if (c === '\n') {
      state.line++;
      i++;
    } else if (/\s/.test(c)) {
      // JS \s also covers the U+FEFF byte-order mark.
      i++;
    } else if (c === '/' && src[i + 1] === '/') {
      while (i < src.length && src[i] !== '\n') i++;
    } else if (c === '/' && src[i + 1] === '*') {
      i = skipBlockComment(src, i, state);
    } else if (c === "'" || c === '"' || (c === 'r' && (src[i + 1] === "'" || src[i + 1] === '"'))) {
      i = skipString(src, i, state);
      tokens.push({ t: 'str', v: '', line, pos, end: i });
    } else if (IDENT_START.test(c)) {
      while (i < src.length && IDENT_PART.test(src[i])) i++;
      tokens.push({ t: 'id', v: src.slice(pos, i), line, pos, end: i });
    } else if (/[0-9]/.test(c) || (c === '.' && /[0-9]/.test(src[i + 1] ?? ''))) {
      i++;
      while (i < src.length && (/[0-9A-Za-z_]/.test(src[i]) || (src[i] === '.' && /[0-9]/.test(src[i + 1] ?? '')))) i++;
      tokens.push({ t: 'num', v: src.slice(pos, i), line, pos, end: i });
    } else {
      const op = DART_OPERATORS.find((o) => src.startsWith(o, i)) ?? c;
      i += op.length;
      tokens.push({ t: 'op', v: op, line, pos, end: i });
    }
  }
  return tokens;
}

const isOp = (tok, v) => tok !== undefined && tok.t === 'op' && tok.v === v;
const isId = (tok, v) => tok !== undefined && tok.t === 'id' && tok.v === v;
const isClosingAngles = (tok) => tok !== undefined && tok.t === 'op' && /^>+$/.test(tok.v);

// Index just after the group that opens at tokens[i] ( `(`, `[` or `{` ).
function skipGroup(tokens, i) {
  let depth = 0;
  for (; i < tokens.length; i++) {
    const tok = tokens[i];
    if (tok.t !== 'op') continue;
    if (tok.v === '(' || tok.v === '[' || tok.v === '{') depth++;
    else if (tok.v === ')' || tok.v === ']' || tok.v === '}') {
      depth--;
      if (depth === 0) return i + 1;
    }
  }
  return tokens.length;
}

// Index just after the `;` that ends the construct at depth 0, or of the
// closer that ends the enclosing body.
function skipToSemicolon(tokens, i, end = tokens.length) {
  while (i < end) {
    const tok = tokens[i];
    if (tok.t === 'op') {
      if (tok.v === '(' || tok.v === '[' || tok.v === '{') {
        i = skipGroup(tokens, i);
        continue;
      }
      if (tok.v === ')' || tok.v === ']' || tok.v === '}') return i;
      if (tok.v === ';') return i + 1;
    }
    i++;
  }
  return i;
}

// Index just after the `<...>` that opens at tokens[i].
function skipAngles(tokens, i, end) {
  let depth = 0;
  while (i < end) {
    const tok = tokens[i];
    if (isOp(tok, '<')) depth++;
    else if (isClosingAngles(tok)) depth -= tok.v.length;
    else if (isOp(tok, '(') || isOp(tok, '[') || isOp(tok, '{')) {
      i = skipGroup(tokens, i);
      continue;
    }
    i++;
    if (depth <= 0) return i;
  }
  return i;
}

// Index just after the annotation that starts at tokens[i] (`@`). Arguments
// belong to it only when `(` follows the name with no space (Dart 3).
function skipAnnotation(tokens, i, end) {
  i += 2;
  while (isOp(tokens[i], '.') && tokens[i + 1]?.t === 'id') i += 2;
  if (isOp(tokens[i], '<') && tokens[i].pos === tokens[i - 1].end) i = skipAngles(tokens, i, end);
  if (isOp(tokens[i], '(') && tokens[i].pos === tokens[i - 1].end) i = skipGroup(tokens, i);
  return i;
}

const CLASS_MODIFIERS = new Set(['abstract', 'base', 'final', 'interface', 'sealed', 'macro', 'augment']);
// Words that can stand right before `(` in a declaration without naming it:
// the `(` then opens a record type.
const NOT_A_NAME = new Set([
  'static', 'final', 'const', 'late', 'var', 'covariant', 'required', 'external',
  'abstract', 'factory', 'augment', 'Function',
]);

// The first token of a user-definable operator's name (`[` for [] and []=).
// A field may be called `operator`; then no such token follows.
const OPERATOR_NAMES = new Set([
  '==', '<', '>', '<=', '>=', '-', '+', '/', '~/', '*', '%', '|', '^', '&',
  '<<', '>>', '>>>', '[', '~',
]);

// { kind, name, next } when a class, mixin, enum or extension starts at
// tokens[i]; next is the index after its name.
function classLike(tokens, i) {
  let k = i;
  while (tokens[k]?.t === 'id' && CLASS_MODIFIERS.has(tokens[k].v)) k++;
  if (isId(tokens[k], 'mixin') && isId(tokens[k + 1], 'class')) k++;
  const keyword = tokens[k];
  if (keyword?.t !== 'id') return null;
  if (keyword.v === 'extension') {
    // An unnamed extension may have type parameters: extension<T> on X.
    if (isOp(tokens[k + 1], '<')) {
      const n = skipAngles(tokens, k + 1, tokens.length);
      return isId(tokens[n], 'on') ? { kind: 'extension', name: '<extension>', next: n } : null;
    }
    if (isId(tokens[k + 1], 'type')) {
      const n = isId(tokens[k + 2], 'const') ? k + 3 : k + 2;
      return tokens[n]?.t === 'id' ? { kind: 'extension type', name: tokens[n].v, next: n + 1 } : null;
    }
    if (isId(tokens[k + 1], 'on')) return { kind: 'extension', name: '<extension>', next: k + 1 };
    return tokens[k + 1]?.t === 'id' ? { kind: 'extension', name: tokens[k + 1].v, next: k + 2 } : null;
  }
  if (!['class', 'mixin', 'enum'].includes(keyword.v) || tokens[k + 1]?.t !== 'id') return null;
  return { kind: keyword.v, name: tokens[k + 1].v, next: k + 2 };
}

// The function a declaration names when its parameter list opens at
// tokens[k], or null when that `(` belongs to a type (a record, or
// `Function(...)`). j is where the declaration's modifiers start.
function functionName(tokens, j, k, owner) {
  let n = k - 1;
  if (isClosingAngles(tokens[n])) {
    // Type parameters: foo<T>( . Walk back to their `<`.
    let depth = 0;
    for (; n >= j; n--) {
      if (isClosingAngles(tokens[n])) depth += tokens[n].v.length;
      else if (isOp(tokens[n], '<')) {
        depth--;
        if (depth === 0) break;
      }
    }
    n--;
  }
  const name = tokens[n];
  if (n < j || name?.t !== 'id' || name.v === 'Function') return null;
  if (NOT_A_NAME.has(name.v)) {
    // `static (int, int) f()`: a modifier, then a record type. But built-in
    // words can be names too: `set static(v)`, `void factory()`.
    const before = n - 1 >= j ? tokens[n - 1] : undefined;
    const typeEnd = before !== undefined && (
      (before.t === 'id' && !NOT_A_NAME.has(before.v)) ||
      isClosingAngles(before) || isOp(before, '?') || isOp(before, ')'));
    if (!typeEnd) return null;
  }
  const factory = tokens.slice(j, n).some((tok) => isId(tok, 'factory'));
  if (n - 2 >= j && isOp(tokens[n - 1], '.') && tokens[n - 2].t === 'id') {
    return { name: `${tokens[n - 2].v}.${name.v}`, kind: factory ? 'factory' : 'constructor', ctor: true };
  }
  if (n - 1 >= j && isId(tokens[n - 1], 'set')) return { name: name.v, kind: 'setter', ctor: false };
  if (owner !== null && name.v === owner) return { name: owner, kind: factory ? 'factory' : 'constructor', ctor: true };
  return { name: name.v, kind: owner === null ? 'function' : 'method', ctor: false };
}

// A token that can end an expression, so a `{` after it opens a body.
function endsExpression(tok) {
  if (tok === undefined) return false;
  if (tok.t === 'str' || tok.t === 'num') return true;
  if (tok.t === 'id') return tok.v !== 'const' && tok.v !== 'new';
  // `!` here is the postfix null check (`: x = y! {`).
  return tok.v === ')' || tok.v === ']' || tok.v === '}' || tok.v === '!';
}

// What follows a declaration's parameters (or a getter's name) at tokens[p]:
// { end, fn } with fn null when the declaration has no body of its own.
function functionBody(tokens, p, end, info, external) {
  while (isId(tokens[p], 'async') || isId(tokens[p], 'sync')) {
    p++;
    if (isOp(tokens[p], '*')) p++;
  }
  const tok = tokens[p];
  const fn = external ? null : info;
  if (isOp(tok, '{')) return { end: skipGroup(tokens, p), fn };
  if (isOp(tok, '=>')) return { end: skipToSemicolon(tokens, p, end), fn };
  if (isOp(tok, ':') && info.ctor) {
    // Initializer list, then the body or `;`. A `{` right after an operator
    // is a literal inside an initializer, not the body.
    let q = p + 1;
    while (q < end) {
      const u = tokens[q];
      if (isOp(u, ';')) return { end: q + 1, fn };
      if (isOp(u, '{') && endsExpression(tokens[q - 1])) return { end: skipGroup(tokens, q), fn };
      if (isOp(u, '(') || isOp(u, '[') || isOp(u, '{')) q = skipGroup(tokens, q);
      else q++;
    }
    return { end: q, fn };
  }
  // A redirecting factory (`= Other;`) has no body of its own.
  if (isOp(tok, '=') && info.ctor) return { end: skipToSemicolon(tokens, p, end), fn: null };
  // No body: a constructor still is a function; a method is abstract.
  if (isOp(tok, ';')) return { end: p + 1, fn: info.ctor ? fn : null };
  return { end: skipToSemicolon(tokens, p, end), fn: null };
}

// One declaration whose modifiers or type start at tokens[j] (annotations
// already skipped): { end, fn }.
function member(tokens, j, end, owner) {
  let angle = 0;
  let external = false;
  let k = j;
  while (k < end) {
    const tok = tokens[k];
    if (tok.t === 'op') {
      if (tok.v === '<') {
        angle++;
        k++;
      } else if (isClosingAngles(tok)) {
        angle -= tok.v.length;
        k++;
      } else if (angle > 0) {
        k = tok.v === '(' || tok.v === '[' || tok.v === '{' ? skipGroup(tokens, k) : k + 1;
      } else if (tok.v === '(') {
        const info = functionName(tokens, j, k, owner);
        if (info === null) k = skipGroup(tokens, k);
        else return functionBody(tokens, skipGroup(tokens, k), end, info, external);
      } else if (tok.v === '=' || tok.v === ';') {
        // A field or variable (or an abstract getter reached without a name).
        return { end: tok.v === ';' ? k + 1 : skipToSemicolon(tokens, k, end), fn: null };
      } else if (tok.v === '{' || tok.v === '[') {
        k = skipGroup(tokens, k);
        if (tok.v === '{') return { end: k, fn: null };
      } else if (tok.v === '}') {
        return { end: k, fn: null };
      } else {
        k++;
      }
      continue;
    }
    if (tok.t === 'id' && angle === 0) {
      // The modifier comes first (`external static ...`); later it is a name.
      if (tok.v === 'external' && tokens.slice(j, k).every((t) => isId(t, 'augment'))) external = true;
      const next = tokens[k + 1];
      const after = tokens[k + 2];
      if (tok.v === 'get' && next?.t === 'id' && after !== undefined &&
          (isOp(after, '=>') || isOp(after, '{') || isOp(after, ';') || isId(after, 'async') || isId(after, 'sync'))) {
        return functionBody(tokens, k + 2, end, { name: next.v, kind: 'getter', ctor: false }, external);
      }
      if (tok.v === 'operator' && next?.t === 'op' && OPERATOR_NAMES.has(next.v)) {
        let n = k + 1;
        let name = '';
        while (n < end && !isOp(tokens[n], '(')) name += tokens[n++].v;
        return functionBody(tokens, skipGroup(tokens, n), end, { name: `operator ${name}`, kind: 'operator', ctor: false }, external);
      }
    }
    k++;
  }
  return { end: k, fn: null };
}

// Declarations in tokens[i, end), owned by the class named owner (null at the
// top level), appended to out as { name, kind, line }.
function scanDeclarations(tokens, i, end, owner, out) {
  while (i < end) {
    const start = i;
    if (isOp(tokens[i], ';')) {
      i++;
      continue;
    }
    let j = i;
    while (isOp(tokens[j], '@') && tokens[j + 1]?.t === 'id') j = skipAnnotation(tokens, j, end);
    const first = tokens[j];
    if (first === undefined || j >= end) break;
    if (owner === null && first.t === 'id' && ['import', 'export', 'library', 'part', 'typedef'].includes(first.v)) {
      i = skipToSemicolon(tokens, j, end);
      continue;
    }
    const cls = owner === null ? classLike(tokens, j) : null;
    if (cls !== null) {
      let k = cls.next;
      while (k < end && !isOp(tokens[k], '{') && !isOp(tokens[k], ';')) {
        k = isOp(tokens[k], '(') || isOp(tokens[k], '[') ? skipGroup(tokens, k) : k + 1;
      }
      if (!isOp(tokens[k], '{')) {
        i = k + 1;
        continue;
      }
      const close = skipGroup(tokens, k);
      let bodyStart = k + 1;
      if (cls.kind === 'enum') {
        // The values come first, up to `;` (or the end of the body).
        bodyStart = skipToSemicolon(tokens, bodyStart, close - 1);
      }
      const members = [];
      scanDeclarations(tokens, bodyStart, close - 1, cls.name, members);
      if (cls.kind === 'enum' && !members.some((fn) => fn.kind === 'constructor' || fn.kind === 'factory')) {
        // An enum that declares no constructor gets one from the compiler,
        // on the enum's first line. The VM lists it (package:coverage
        // counts it), and like every enum constructor it never runs: the
        // values are constants.
        members.unshift({ name: cls.name, kind: 'implicit constructor', line: tokens[start].line });
      }
      out.push(...members);
      i = close;
      continue;
    }
    const r = member(tokens, j, end, owner);
    if (r.fn !== null) out.push({ name: owner === null || r.fn.ctor ? r.fn.name : `${owner}.${r.fn.name}`, kind: r.fn.kind, line: tokens[start].line });
    i = Math.max(r.end, j + 1);
  }
}

/** The functions package:coverage would list for Dart source [src]. */
export function dartFunctions(src) {
  const tokens = lexDart(src);
  const out = [];
  scanDeclarations(tokens, 0, tokens.length, null, out);
  return out;
}

const hasFunctionRecords = (rec) => rec.summary.FNF !== undefined || rec.fn.size > 0;

// Function totals for one lcov record [rec] (from parseLcov): its FN/FNDA
// records when it has them, else derived from the Dart source [src] and the
// line hits. [src] null means the source is not there: no totals.
export function functionTotalsFrom(rec, src) {
  const s = rec.summary;
  if (hasFunctionRecords(rec)) {
    const total = s.FNF ?? rec.fn.size;
    const missed = [...rec.fn.keys()].filter((name) => (rec.fnda.get(name) ?? 0) === 0);
    return { totals: [s.FNH ?? total - missed.length, total], missed, source: 'lcov' };
  }
  if (src === null) return { totals: null, missed: [], source: null };
  const fns = dartFunctions(src);
  const missed = fns.filter((fn) => !((rec.da.get(fn.line) ?? 0) > 0)).map((fn) => `${fn.name}@${fn.line}`);
  return { totals: [fns.length - missed.length, fns.length], missed, source: 'derived' };
}

// functionTotalsFrom with the source at pkg/<path>, read only when needed.
export function functionTotals(rec, pkg) {
  if (hasFunctionRecords(rec)) return functionTotalsFrom(rec, null);
  const file = path.join(pkg, rec.path);
  return functionTotalsFrom(rec, fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null);
}

function fileTotals(rec, pkg) {
  const s = rec.summary;
  const linesTotal = s.LF ?? rec.da.size;
  const linesCovered = s.LH ?? [...rec.da.values()].filter((hits) => hits > 0).length;
  const hasBranches = s.BRF !== undefined || rec.brda.length > 0;
  const branchesTotal = s.BRF ?? rec.brda.length;
  const branchesCovered = s.BRH ?? rec.brda.filter((b) => b.taken !== '-' && Number(b.taken) > 0).length;
  const functions = functionTotals(rec, pkg);
  return {
    lines: [linesCovered, linesTotal],
    branches: hasBranches ? [branchesCovered, branchesTotal] : null,
    functions: functions.totals,
    missedFunctions: functions.missed,
    functionsSource: functions.source,
  };
}

// "3,7-9,12" from a sorted list of line numbers.
function compressLines(lines) {
  const out = [];
  for (let i = 0; i < lines.length; i++) {
    let j = i;
    while (j + 1 < lines.length && lines[j + 1] === lines[j] + 1) j++;
    out.push(i === j ? `${lines[i]}` : `${lines[i]}-${lines[j]}`);
    i = j;
  }
  return out.join(',');
}

function globToRegExp(glob) {
  let re = '';
  for (let i = 0; i < glob.length; i++) {
    const c = glob[i];
    if (c === '*' && glob[i + 1] === '*') {
      re += '.*';
      i++;
      if (glob[i + 1] === '/') i++;
    } else if (c === '*') {
      re += '[^/]*';
    } else {
      re += c.replace(/[.+?^${}()|[\]\\]/g, '\\$&');
    }
  }
  return new RegExp(`^${re}$`);
}

const matchesAny = (file, globs) => globs.some((g) => globToRegExp(g).test(file));

function listDartFiles(pkg, dir) {
  const root = path.join(pkg, dir);
  if (!fs.existsSync(root)) return [];
  const out = [];
  for (const entry of fs.readdirSync(root, { withFileTypes: true, recursive: true })) {
    if (entry.isFile() && entry.name.endsWith('.dart')) {
      out.push(path.relative(pkg, path.join(entry.parentPath ?? entry.path, entry.name)).split(path.sep).join('/'));
    }
  }
  return out.sort();
}

// True when a file holds only comments and library/import/export/part
// directives (a barrel). Such a file has no executable lines, so it never
// shows up in lcov.info; the unmeasured check says so.
function isDirectivesOnly(text) {
  const code = text
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .split('\n')
    .map((line) => line.replace(/\/\/.*$/, '').trim())
    .filter((line) => line.length > 0)
    .join('\n');
  const statements = code.split(';').map((st) => st.trim()).filter((st) => st.length > 0);
  return statements.every((st) => /^(library|import|export|part)\b/.test(st));
}

const IGNORE_RE = /\/\/\s*coverage:(ignore-line|ignore-start|ignore-end|ignore-file)\b[\s:—–-]*(.*)$/;

// Every coverage:ignore-* comment, with the text after it as the reason.
// ignore-end closes a block and needs no reason of its own.
export function scanIgnores(pkg, files) {
  const ignores = [];
  for (const file of files) {
    const lines = fs.readFileSync(path.join(pkg, file), 'utf8').split('\n');
    lines.forEach((text, index) => {
      const m = IGNORE_RE.exec(text);
      if (!m) return;
      const reason = m[2].trim() || null;
      ignores.push({ path: file, line: index + 1, directive: m[1], reason });
    });
  }
  return ignores;
}

/** Whether an ignore's [reason] names an A10 category (any case). */
export function namesA10(reason) {
  const text = (reason ?? '').toLowerCase();
  return Object.values(A10).some((category) => text.includes(category));
}

// What is wrong with the coverage:ignore-* comments [ignores] (from
// scanIgnores): one without a reason; an ignore-line or ignore-start whose
// reason names no A10 category; an ignore-file on a file [isExcluded] says
// EXCLUDED does not list (EXCLUDED holds its A10 category, so a generated
// file's own ignore-file text needs none).
export function ignoreProblems(ignores, isExcluded) {
  const problems = [];
  for (const i of ignores) {
    if (i.directive === 'ignore-end') continue;
    const where = `${i.path}:${i.line}`;
    if (i.reason === null) {
      problems.push(`coverage:${i.directive} without a reason: ${where}`);
    } else if (i.directive !== 'ignore-file' && !namesA10(i.reason)) {
      problems.push(`coverage:${i.directive} reason names no A10 category (${Object.values(A10).join(', ')}): ${where}`);
    }
    if (i.directive === 'ignore-file' && !isExcluded(i.path)) {
      problems.push(`coverage:ignore-file on a file EXCLUDED does not list with an A10 category: ${where}`);
    }
  }
  return problems;
}

function aggregate(entries, key) {
  const present = entries.filter((e) => e.totals[key] !== null);
  if (present.length === 0) return null;
  const covered = present.reduce((sum, e) => sum + e.totals[key][0], 0);
  const total = present.reduce((sum, e) => sum + e.totals[key][1], 0);
  return counts(covered, total);
}

// Totals for one scope. With unmeasured files the pct values are withheld
// (null), since the missing files would only lower them.
function summarize(entries, unmeasured) {
  const complete = unmeasured.length === 0;
  const scope = (metric) => (metric === null || complete ? metric : { ...metric, pct: null });
  return {
    complete,
    lines: scope(aggregate(entries, 'lines')),
    branches: scope(aggregate(entries, 'branches')),
    regions: null,
    functions: scope(aggregate(entries, 'functions')),
  };
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const pkg = path.resolve(args.pkg);
  const lcovText = fs.readFileSync(args.lcov, 'utf8');
  const records = parseLcov(lcovText);
  if (records.size === 0) throw new Error(`${args.lcov} has no SF records`);

  const libFiles = listDartFiles(pkg, 'lib');
  const ignores = scanIgnores(pkg, libFiles);
  const excluded = EXCLUDED.map((e) => ({ path: e.path, a10: e.a10, reason: e.reason }));
  const isExcluded = (file) => matchesAny(file, excluded.map((e) => e.path));

  const entries = [...records.values()]
    .filter((rec) => matchesAny(rec.path, WHOLE_INCLUDE))
    .map((rec) => ({
      path: rec.path,
      totals: fileTotals(rec, pkg),
      missed: [...rec.da].filter(([, hits]) => hits === 0).map(([line]) => line).sort((a, b) => a - b),
      missedBranch: [...new Set(rec.brda.filter((b) => b.taken === '-' || Number(b.taken) === 0).map((b) => b.line))].sort((a, b) => a - b),
      inGate: matchesAny(rec.path, GATE_INCLUDE) && !isExcluded(rec.path),
    }))
    .sort((a, b) => a.path.localeCompare(b.path));

  const measured = new Set(entries.map((e) => e.path));
  const unmeasured = libFiles.filter((file) => !measured.has(file) && !isExcluded(file));
  const gateUnmeasured = unmeasured.filter((file) => matchesAny(file, GATE_INCLUDE));
  const sources = new Set(entries.map((e) => e.totals.functionsSource).filter((s) => s !== null));

  const pctOf = (pair) => (pair === null ? null : counts(pair[0], pair[1]).pct);
  const summary = {
    platform: 'flutter',
    generatedAt: new Date().toISOString(),
    tool: 'flutter test --coverage --branch-coverage (package:coverage lcov); functions derived by flutter-summary.mjs',
    commands: args.commands,
    gate: {
      include: GATE_INCLUDE,
      exclude: excluded.map((e) => e.path),
      ...summarize(entries.filter((e) => e.inGate), gateUnmeasured),
      unmeasured: gateUnmeasured,
    },
    whole: { include: WHOLE_INCLUDE, ...summarize(entries, unmeasured), unmeasured },
    functionsSource: sources.size === 0 ? null : [...sources].sort().join('+'),
    excluded,
    ignoredLines: ignores,
    perFile: [
      ...entries.map((e) => ({
        path: e.path,
        lines: pctOf(e.totals.lines),
        branches: pctOf(e.totals.branches),
        functions: pctOf(e.totals.functions),
        inGate: e.inGate,
        linesCovered: e.totals.lines[0],
        linesTotal: e.totals.lines[1],
        branchesCovered: e.totals.branches?.[0] ?? null,
        branchesTotal: e.totals.branches?.[1] ?? null,
        functionsCovered: e.totals.functions?.[0] ?? null,
        functionsTotal: e.totals.functions?.[1] ?? null,
        missedLines: compressLines(e.missed),
        missedBranchLines: compressLines(e.missedBranch),
        missedFunctions: e.totals.missedFunctions,
      })),
      ...unmeasured.map((file) => ({
        path: file,
        lines: null,
        branches: null,
        functions: null,
        inGate: matchesAny(file, GATE_INCLUDE),
        measured: false,
      })),
      // Excluded files lcov.info does not list, so every lib/ file shows.
      ...libFiles.filter((file) => isExcluded(file) && !measured.has(file)).map((file) => ({
        path: file,
        lines: null,
        branches: null,
        functions: null,
        inGate: false,
        measured: false,
        excluded: excluded.find((e) => matchesAny(file, [e.path])).a10,
      })),
    ],
    tests: args.testsExit === undefined ? null : { exitCode: args.testsExit, passed: args.testsExit === 0 },
    contracts: args.contracts ?? null,
    contractsHarness: args.contractsHarness ?? null,
    notes: NOTES,
  };

  fs.mkdirSync(path.dirname(args.out), { recursive: true });
  fs.writeFileSync(args.out, `${JSON.stringify(summary, null, 2)}\n`);

  const problems = [];
  const a10Values = new Set(Object.values(A10));
  for (const e of EXCLUDED) {
    if (!a10Values.has(e.a10)) problems.push(`exclusion without an A10 category: ${e.path}`);
    if (!e.reason) problems.push(`exclusion without a reason: ${e.path}`);
    if (!libFiles.some((file) => matchesAny(file, [e.path]))) problems.push(`exclusion matches no file (stale): ${e.path}`);
  }
  problems.push(...ignoreProblems(ignores, isExcluded));
  for (const file of unmeasured) {
    const why = isDirectivesOnly(fs.readFileSync(path.join(pkg, file), 'utf8'))
      ? 'directives only, so it has no executable lines: add it to EXCLUDED with an A10 category'
      : 'load it from a test, or add it to EXCLUDED with an A10 category';
    problems.push(`not in lcov.info (${why}): ${file}`);
  }
  const below = (metric) => metric !== null && metric.total > 0 && (metric.covered / metric.total) * 100 < TARGET_PCT;
  const pctText = (m) => `${counts(m.covered, m.total).pct}%${m.pct === null ? ' (measured files only)' : ''}`;
  if (below(summary.gate.lines)) problems.push(`gate lines ${pctText(summary.gate.lines)} < ${TARGET_PCT}%`);
  if (below(summary.gate.branches)) problems.push(`gate branches ${pctText(summary.gate.branches)} < ${TARGET_PCT}%`);
  if (below(summary.gate.functions)) problems.push(`gate functions ${pctText(summary.gate.functions)} < ${TARGET_PCT}%`);
  if (summary.gate.functions === null) problems.push('gate functions not measured');

  const fmt = (m) => {
    if (m === null) return 'n/a';
    return m.pct === null ? `${m.covered}/${m.total} measured files only (pct withheld)` : `${m.covered}/${m.total} (${m.pct}%)`;
  };
  const row = (scope) => `lines ${fmt(scope.lines)}  branches ${fmt(scope.branches)}  functions ${fmt(scope.functions)}`;
  process.stdout.write(
    `flutter coverage -> ${args.out}\n` +
    `  gate  ${row(summary.gate)}\n` +
    `  whole ${row(summary.whole)}\n`,
  );
  for (const p of problems) process.stderr.write(`  ! ${p}\n`);
  if (args.enforce && problems.length > 0) process.exitCode = 2;
}

// `--functions <file.dart>...`: what dartFunctions finds, for checking it.
function listFunctions(files) {
  const out = files.map((file) => ({ file, functions: dartFunctions(fs.readFileSync(file, 'utf8')) }));
  process.stdout.write(`${JSON.stringify(out, null, 2)}\n`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  try {
    if (process.argv[2] === '--functions') listFunctions(process.argv.slice(3));
    else main();
  } catch (error) {
    process.stderr.write(`flutter-summary: ${error.message}\n`);
    process.exitCode = 1;
  }
}
